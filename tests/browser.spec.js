  await expect(page.getByRole('heading', { name: 'October 2026' })).toBeVisible();
  await expect(page.getByText('£128.42', { exact: true }).first()).toBeVisible();
  expect(await page.evaluate(key => localStorage.getItem(key), STORAGE_KEY)).toBeNull();
  if (process.env.APP_SCREENSHOT_DIR) {
    await mkdir(process.env.APP_SCREENSHOT_DIR, { recursive: true });
    await page.screenshot({ path: resolve(process.env.APP_SCREENSHOT_DIR, 'commonplace-desktop.png'), fullPage: true });
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  if (process.env.APP_SCREENSHOT_DIR) await page.screenshot({ path: resolve(process.env.APP_SCREENSHOT_DIR, 'commonplace-mobile.png'), fullPage: true });
  const overflow = await page.evaluate(() => [...document.querySelectorAll('body *')].filter(el => el.getBoundingClientRect().right > innerWidth && !el.closest('.table-wrap') && !el.closest('nav')).map(el => ({ tag: el.tagName, class: el.className, right: el.getBoundingClientRect().right })));
  expect(overflow).toEqual([]);
  await page.locator('.demo-banner button').click();
  await expect(page.getByText('Your ledger starts here')).toBeVisible();
