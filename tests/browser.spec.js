test('concurrent tabs refuse stale writes instead of silently overwriting', async ({ page, context }) => {
  await page.goto('/');
  const other = await context.newPage(); await other.goto('/'); await nav(other, 'settings');
  await other.locator('[name=account-personal]').fill('Changed by second tab');
  await other.getByRole('button', { name: 'Save settings' }).click();
  await page.getByRole('button', { name: '+ Add transaction', exact: true }).click();
  await page.locator('[name=description]').fill('Stale purchase'); await page.locator('[name=amount]').fill('10');
  await page.getByRole('button', { name: 'Add & review' }).click();
  await expect(page.locator('.form-error')).toContainText('Another tab changed this ledger');
  const s = await page.evaluate(key => JSON.parse(localStorage.getItem(key)), STORAGE_KEY);
  expect(s.transactions).toHaveLength(0); expect(s.accounts[0].name).toBe('Changed by second tab');
  await other.close();
});
